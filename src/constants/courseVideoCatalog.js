/**
 * Resolves a course identifier (id, string id, slug) to canonical course video entry.
 * @param {string|number} courseIdOrSlug
 * @returns {object|null}
 */
export const getCourseVideo = (courseIdOrSlug) => {
  if (!courseIdOrSlug) return null;
  const key = String(courseIdOrSlug).toLowerCase().trim();

  // Direct numeric match in catalog
  if (COURSE_VIDEO_CATALOG[key]) {
    return COURSE_VIDEO_CATALOG[key];
  }

  // Alias lookup
  const canonicalId = ALIAS_MAP[key];
  if (canonicalId && COURSE_VIDEO_CATALOG[canonicalId]) {
    return COURSE_VIDEO_CATALOG[canonicalId];
  }

  return null;
};

/**
 * Extracts Google Drive File ID from preview / view / download / uc / open URLs.
 * @param {string} url
 * @returns {string|null}
 */
export const extractGoogleDriveId = (url = "") => {
  if (!url || typeof url !== "string") return null;
  const trimmed = url.trim();

  // /file/d/FILE_ID/
  const matchFileD = trimmed.match(/\/file\/d\/([a-zA-Z0-9_-]{25,})/);
  if (matchFileD?.[1]) return matchFileD[1];

  // ?id=FILE_ID or &id=FILE_ID
  const matchParamId = trimmed.match(/[?&]id=([a-zA-Z0-9_-]{25,})/);
  if (matchParamId?.[1]) return matchParamId[1];

  // Raw Google Drive ID directly passed (typically 28 to 33 alphanumeric chars)
  if (/^[a-zA-Z0-9_-]{28,45}$/.test(trimmed)) {
    return trimmed;
  }

  return null;
};

/**
 * Extracts YouTube Video ID from any standard or shortened YouTube URL.
 * @param {string} url
 * @returns {string|null}
 */
export const extractYouTubeId = (url = "") => {
  if (!url || typeof url !== "string") return null;
  const trimmed = url.trim();

  if (/^[a-zA-Z0-9_-]{11}$/.test(trimmed)) {
    return trimmed;
  }

  const matchWatch = trimmed.match(/(?:youtube\.com\/watch\?v=)([a-zA-Z0-9_-]{11})/);
  if (matchWatch?.[1]) return matchWatch[1];

  const matchShort = trimmed.match(/youtu\.be\/([a-zA-Z0-9_-]{11})/);
  if (matchShort?.[1]) return matchShort[1];

  const matchEmbed = trimmed.match(/youtube(?:-nocookie)?\.com\/embed\/([a-zA-Z0-9_-]{11})/);
  if (matchEmbed?.[1]) return matchEmbed[1];

  const matchShorts = trimmed.match(/youtube\.com\/shorts\/([a-zA-Z0-9_-]{11})/);
  if (matchShorts?.[1]) return matchShorts[1];

  return null;
};

