/**
 * Multi-provider video embed URL resolver:
 * Handles:
 * 1. Course-specific Google Drive video priority
 * 2. Google Drive URLs & IDs -> Standardized embeddable /preview URL
 * 3. YouTube URLs & IDs (Strictly filtering out obsolete placeholders)
 * 4. Direct video URLs (mp4, webm) -> untouched for HTML5 video
 * 5. Fallback lookup to COURSE_VIDEO_CATALOG by courseId
 *
 * @param {string} videoSource - lesson.video_url or any video link
 * @param {string|number} [courseIdOrSlug] - optional fallback course identifier
 * @returns {string} - embeddable iframe URL or video stream source
 */
export const resolveVideoEmbedUrl = (videoSource = "", courseIdOrSlug = null) => {
  const source = String(videoSource || "").trim();
  const courseVideo = courseIdOrSlug ? getCourseVideo(courseIdOrSlug) : null;

  // 1. Google Drive source detection from input
  const driveId = extractGoogleDriveId(source);
  if (driveId) {
    return `https://drive.google.com/file/d/${driveId}/preview`;
  }

  // 2. Direct video file stream (MP4 / WebM / M4V)
  if (/\.(mp4|webm|ogg|m4v)(\?.*)?$/i.test(source)) {
    return source;
  }

  // 3. YouTube source detection — FILTER OUT OBSOLETE IDS
  const ytId = extractYouTubeId(source);
  if (ytId && !OBSOLETE_YOUTUBE_IDS.has(ytId)) {
    return `https://www.youtube-nocookie.com/embed/${ytId}?rel=0&controls=1&playsinline=1&modestbranding=1`;
  }

  // 4. Primary Authoritative Course Video from Catalog
  if (courseVideo?.embedUrl) {
    return courseVideo.embedUrl;
  }

  // 5. If source already has valid non-obsolete https URL, return as-is
  if (/^https?:\/\//i.test(source) && !OBSOLETE_YOUTUBE_IDS.has(ytId)) {
    return source;
  }

  return "";
};

